// One Africa Life: the shops and offices walked into, against the development project. In the
// phone shop on Tubman Boulevard a phone is picked up from its stand, put down on the counter,
// paid for, boxed by the seller and carried off; at Starline Mobile's customer care a ticket is
// taken, the number called, a SIM bought and registered at the desk (the form, the passport, the
// photograph, the fingerprints) and the welcome text comes; at the Ministry of Health a birth
// certificate is applied for, a text says it is ready, and it is collected.
// Run with: npm run on-dev -- e2e -- e2e/oal-shops.spec.ts --headed (SHOTS=<dir> for pictures)
import { expect, type Page, test } from '@playwright/test'
import { goTo } from './oalWorld.ts'
import { runSql } from '../scripts/lib/managementApi.ts'
import { ensureTestAccounts, resetTestAccounts, TEST_ACCOUNTS, TEST_PASSWORD } from '../scripts/lib/testAccounts.ts'
test.setTimeout(900_000)
test.beforeAll(ensureTestAccounts)
test.beforeEach(resetTestAccounts)
const APPEARANCE = { version: 1, sex: 'female', skin: 0.8, build: { weight: 0.2, muscle: 0, height: 0 }, face: { noseWidth: 0, noseLength: 0, lips: 0, mouthWidth: 0, jaw: 0, chin: 0, cheekbones: 0, eyes: 0 }, hair: 'braids', hairColour: 'black', eyes: 'darkbrown', outfit: 'blouse_skirt' }
const shot = async (page: Page, name: string) => {
  if (process.env.SHOTS) await page.screenshot({ path: `${process.env.SHOTS}/${name}.png` })
}
async function hold(page: Page, key: string, ms: number) {
  await page.keyboard.down(key)
  await page.waitForTimeout(ms)
  await page.keyboard.up(key)
  await page.waitForTimeout(300)
}
test('a phone from the shop, a SIM registered, a birth certificate', async ({ page }) => {
  const account = TEST_ACCOUNTS[1]!
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  const [me] = await runSql<{ id: string }>(`select id from auth.users where email = '${account.email}'`)
  await runSql(`select public.oal_start_life('${me!.id}', 'Musu Kollie', 'female', 26, 'LR', 'Monrovia', '${JSON.stringify(APPEARANCE)}'::jsonb)`)
  await runSql(`select private.oal_money('${me!.id}', 'LRD', 5000000, 'adjustment')`)
  await runSql(`insert into public.oal_passports (user_id, country, number, issued_on, expires_on) values ('${me!.id}', 'LR', 'R1234567', '2026-01-01', '2036-01-01') on conflict do nothing`)
  await page.goto('/login')
  await page.getByLabel('Email').fill(account.email)
  await page.getByLabel('Password').fill(TEST_PASSWORD)
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page).toHaveURL(/\/lobby$/, { timeout: 20_000 })
  await page.goto('/life')
  await goTo(page, 'sinkor', 'phone')
  await expect(page.getByTestId('oal-home-view')).toHaveAttribute('data-kind', 'phoneshop', { timeout: 120_000 })
  await page.waitForTimeout(4000)
  await shot(page, 'shop1')
  await hold(page, 'ArrowRight', 2200)
  await shot(page, 'shop2')
  await page.getByTestId('oal-look-phone').click({ timeout: 10_000 })
  await shot(page, 'shop3')
  await page.getByTestId('oal-pick-up').click()
  await page.waitForTimeout(1100)
  await shot(page, 'shop3b')
  await expect(page.getByTestId('oal-carrying')).toBeVisible()
  await page.waitForTimeout(2600)
  await shot(page, 'shop3c')
  await hold(page, 'ArrowLeft', 2300)
  await hold(page, 'ArrowUp', 2900)
  await page.getByTestId('oal-put-down').click({ timeout: 10_000 })
  await page.waitForTimeout(1300)
  await shot(page, 'shop4')
  await page.waitForTimeout(2500)
  await page.getByTestId('oal-home-menu').click()
  await page.getByTestId('oal-pay-phone').click()
  await expect(page.getByText(/is yours/)).toBeVisible({ timeout: 20_000 })
  await page.waitForTimeout(600)
  await shot(page, 'shop5')
  await page.getByTestId('oal-take-box').click({ timeout: 10_000 })
  await page.waitForTimeout(3600)
  await shot(page, 'shop6')
  const [ph] = await runSql<{ handset: string; unboxed: boolean; charge: string }>(`select handset, unboxed, charge from public.oal_phones where user_id = '${me!.id}'`)
  expect(ph).toEqual({ handset: 'lr_smart_plus', unboxed: false, charge: 'flat' })
  console.log('UNBOX', JSON.stringify(await runSql(`select public.oal_phone_box_action('${me!.id}', 'unbox') as r`)))
  console.log('CHARGE', JSON.stringify(await runSql(`select public.oal_phone_box_action('${me!.id}', 'charge') as r`)))
  await runSql(`update public.oal_phones set charged_at = charged_at - interval '2 hours' where user_id = '${me!.id}'`)
  await goTo(page, 'sinkor', 'starline')
  await expect(page.getByTestId('oal-home-view')).toHaveAttribute('data-kind', 'starline', { timeout: 120_000 })
  await page.waitForTimeout(4000)
  await shot(page, 'off1')
  await hold(page, 'ArrowLeft', 3300)
  await page.getByTestId('oal-take-ticket').click({ timeout: 10_000 })
  await hold(page, 'ArrowRight', 3300)
  await hold(page, 'ArrowUp', 3600)
  await shot(page, 'off2')
  await page.waitForTimeout(9000)
  await page.getByTestId('oal-home-menu').click()
  await page.getByTestId('oal-buy-sim-lr_starline').click({ timeout: 30_000 })
  await page.getByTestId('oal-sim-address').fill('Sinkor, 16th Street')
  await page.getByTestId('oal-register-lr_starline').click()
  await page.getByRole('button', { name: 'Done' }).first().click()
  await page.waitForTimeout(2200)
  await shot(page, 'off3')
  await page.waitForTimeout(3000)
  await shot(page, 'off4')
  await page.waitForTimeout(4500)
  await page.getByTestId('oal-home-menu').click()
  await expect(page.getByTestId('oal-number-lr_starline')).toBeVisible({ timeout: 30_000 })
  console.log('TEXTS', JSON.stringify(await runSql(`select from_number, body from public.oal_texts where to_user = '${me!.id}'`)))
  await page.evaluate((id) => localStorage.setItem(`oal-spot:${id}`, JSON.stringify({ area: 'health', place: 'health' })), me!.id)
  await page.reload()
  await expect(page.getByTestId('oal-home-view')).toHaveAttribute('data-kind', 'health', { timeout: 120_000 })
  await page.waitForTimeout(4000)
  await shot(page, 'moh1')
  await hold(page, 'ArrowUp', 4200)
  await hold(page, 'ArrowLeft', 2900)
  await shot(page, 'moh2')
  await page.getByTestId('oal-home-menu').click()
  await page.getByTestId('oal-birth-father').fill('Joseph Kollie')
  await page.getByTestId('oal-birth-mother').fill('Mary Kollie')
  await page.getByTestId('oal-birth-apply').click()
  await expect(page.getByText(/Application received/)).toBeVisible({ timeout: 20_000 })
  await runSql(`update public.oal_birth_certificates set applied_at = applied_at - interval '2 days', ready_at = ready_at - interval '2 days' where user_id = '${me!.id}'`)
  await runSql(`select private.oal_office_notices()`)
  console.log('TEXTS2', JSON.stringify(await runSql(`select from_number, body from public.oal_texts where to_user = '${me!.id}' order by id`)))
  await page.getByRole('button', { name: 'Done' }).first().click()
  await hold(page, 'ArrowRight', 2900)
  await page.getByTestId('oal-home-menu').click()
  await page.getByTestId('oal-birth-collect').click({ timeout: 20_000 })
  await expect(page.getByTestId('oal-birth-certificate')).toBeVisible({ timeout: 20_000 })
  await shot(page, 'moh4')
  expect(errors).toEqual([])
})
